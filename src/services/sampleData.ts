/** Draws a clear, high-resolution handwritten signature for the demo card. */
function makeDemoSignature(name: string, seed: number): string {
  if (typeof document === 'undefined') return '';
  const canvas = document.createElement('canvas');
  canvas.width = 480;
  canvas.height = 96;
  const ctx = canvas.getContext('2d');
  if (!ctx) return '';

  ctx.clearRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = '#1c1917';
  ctx.strokeStyle = '#1c1917';
  ctx.textBaseline = 'middle';
  ctx.font = 'italic 54px "Segoe Script", "Brush Script MT", "Lucida Handwriting", cursive';
  ctx.fillText(name, 20, 47 + seed * 2);

  const width = Math.min(ctx.measureText(name).width + 16, canvas.width - 30);
  ctx.lineWidth = 2.2;
  ctx.lineCap = 'round';
  ctx.beginPath();
  ctx.moveTo(18, 78);
  ctx.bezierCurveTo(width * 0.3, 70 + seed, width * 0.65, 86, width, 75);
  ctx.stroke();

  return canvas.toDataURL('image/png');
}

